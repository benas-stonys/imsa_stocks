test('classroom endpoint uses verified actor, rejects anonymous and malformed requests',async()=>{
  const calls=[];
  const handler=createClassroomHandler({getClient:()=>({auth:{getUser:async()=>({data:{user:{id:'verified-user'}}})},rpc:async(name,args)=>{calls.push(args);return {data:{ok:true}};}})});
  const event={httpMethod:'POST',headers:{authorization:'Bearer token'},body:JSON.stringify({action:'assignment.create',p_actor:'forged',student_id:'forged'})};
  assert.equal((await handler({...event,headers:{}})).statusCode,401);
  assert.equal((await handler({...event,httpMethod:'GET'})).statusCode,405);
  assert.equal((await handler({...event,body:'{'})).statusCode,400);
  assert.equal((await handler({...event,body:'x'.repeat(24001)})).statusCode,400);
  assert.equal((await handler(event)).statusCode,200);
  assert.equal(calls[0].p_actor,'verified-user');
});

test('classroom candles use recorded OHLC only; notes have bounded length',()=>{
  const now=Date.parse('2026-11-04T16:00:00Z');
  const rows=[{recorded_at:'2026-11-04T14:00:00Z',price:100},{recorded_at:'2026-11-04T14:30:00Z',price:130},{recorded_at:'2026-11-04T15:00:00Z',price:110}];
  const c=classroomCandles(rows,'1d','60m',now);
  assert.deepEqual(c.o,[100,110]);assert.deepEqual(c.h,[130,110]);assert.deepEqual(c.c,[130,110]);
  assert.equal(classroomCandles(rows.slice(0,1),'1d','1m',now).t.length,1);
  const order={ticker:'AAPL',action:'buy',shares:1,request_id:randomUUID()};
  assert.throws(()=>validateOrder({...order,rationale:'x'.repeat(2001)}));
  assert.equal(validateOrder({...order,rationale:'My thesis'}).rationale,'My thesis');
});
